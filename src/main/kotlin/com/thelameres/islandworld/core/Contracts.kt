package com.thelameres.islandworld.core

import net.minecraft.server.MinecraftServer
import java.util.*

/**
 * Подсистема мода, которая сама подключается к нужным событиям.
 *
 * Контракт один: `register()` вызывается ровно один раз при инициализации мода
 * и подписывает подсистему на всё, что ей нужно. Что именно она слушает и как
 * хранит состояние — её личное дело, точка сборки об этом не знает.
 *
 * Реализуют все подсистемы, которые раньше вызывались из `onInitialize` поштучно.
 */
interface Registrable {
    fun register()
}

/**
 * Состояние, привязанное к конкретному игроку.
 *
 * Такое состояние нельзя оставлять после выхода игрока: карты по UUID растут
 * безгранично, а после повторного входа в них лежат устаревшие записи.
 * [forget] вызывается на DISCONNECT — реализация обязана удалить всё, что помнит
 * про этого игрока, и ничего не делать, если записей нет.
 *
 * Респавн сюда не входит намеренно: при смерти создаётся новый объект игрока,
 * но часть состояния (например, ожидание респавна на краю острова) ещё нужна
 * обработчику AFTER_RESPAWN. Поэтому очистку на респавне каждая подсистема
 * делает сама в своём `register()`, где порядок относительно других обработчиков
 * очевиден.
 */
interface PlayerScoped {
    fun forget(uuid: UUID)
}

/**
 * Состояние, живущее ровно одну сессию сервера: кэши, счётчики, накопленные флаги.
 *
 * [reset] вызывается на SERVER_STOPPED. Статический объект живёт дольше мира,
 * поэтому без сброса значения переезжают в следующую сессию — в одиночной игре
 * это заметно сразу после выхода в меню и загрузки другого мира.
 */
interface SessionScoped {
    fun reset(server: MinecraftServer)
}


/**
 * Состояние, которое нужно восстановить после старта сервера из сохранённых данных.
 *
 * Для тех, кто хранит долговременные данные в SavedData, но держит рядом transient-объекты,
 * которые создаются заново при каждом запуске и о сохранённом ничего не знают. Пример:
 * [com.thelameres.islandworld.locator.WaypointStore] хранит точки на диске, а WaypointManager
 * пересоздаётся пустым, и без restore точки невидимы, пока соответствующие чанки не загрузятся.
 *
 * [restore] вызывается из [Lifecycle] на SERVER_STARTED, один раз на сервер, до первого тика.
 * Получает весь сервер, потому что нужные данные лежат в разных измерениях.
 *
 * Требования к реализации:
 *  - Не создавать SavedData там, где данных не было: использовать `dataStorage.get(...)`,
 *    а не `computeIfAbsent`. Последний помечает созданный объект грязным, и на диск ляжет
 *    пустой .dat для каждого измерения, где меток никогда не было.
 *  - Не переписывать сохранённые данные: restore только читает и передаёт их дальше.
 *  - Быть идемпотентным относительно повторного вызова в той же сессии, на случай если
 *    порядок подписок изменится.
 *
 * В отличие от [SessionScoped], это не сброс, а восстановление: парный метод отсутствует,
 * потому что сохранённые данные и так переживают остановку сервера.
 */
interface RestoreScoped {
    fun restore(server: MinecraftServer)
}
